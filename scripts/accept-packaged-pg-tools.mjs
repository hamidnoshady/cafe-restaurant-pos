#!/usr/bin/env node
/**
 * Executes the actual packaged pg_dump/pg_restore payload against a disposable
 * PostgreSQL server. This is a release acceptance test, not a mock: it proves
 * custom-format round-trip, UTF-8, exact bigint, FK and sequence restoration,
 * corruption rejection, packaged provenance, and server-major compatibility.
 */
import { spawn } from "node:child_process";
import { promises as fs } from "node:fs";
import os from "node:os";
import path from "node:path";
import process from "node:process";
import { Client } from "pg";

const tools = path.resolve(process.env.PG_TOOLS_DIR || process.argv[2] || "electron/dist/win-unpacked/resources/postgresql-tools");
const sourceUrl = process.env.DATABASE_URL;
const output = path.resolve(process.env.PG_TOOLS_ACCEPTANCE_REPORT || "packaged-pg-tools-acceptance.json");
if (!sourceUrl) throw new Error("DATABASE_URL is required");

const exe = (name) => path.join(tools, "bin", process.platform === "win32" ? `${name}.exe` : name);
const dumpBin = exe("pg_dump");
const restoreBin = exe("pg_restore");

function run(command, args, { expectFailure = false } = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, { windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (chunk) => { stdout += chunk; });
    child.stderr.on("data", (chunk) => { stderr += chunk; });
    child.once("error", reject);
    child.once("close", (code) => {
      if ((code === 0) === expectFailure) reject(new Error(`${path.basename(command)} unexpected exit ${code}: ${stderr.slice(-2000)}`));
      else resolve({ code, stdout, stderr });
    });
  });
}

function databaseUrl(name) {
  const value = new URL(sourceUrl);
  value.pathname = `/${name}`;
  return value.toString();
}

async function sql(url, text, values = []) {
  const client = new Client({ connectionString: url });
  await client.connect();
  try { return await client.query(text, values); } finally { await client.end(); }
}

const suffix = `${process.pid}_${Date.now()}`;
const restoredName = `suite_tools_restore_${suffix}`;
const corruptName = `suite_tools_corrupt_${suffix}`;
const adminUrl = databaseUrl("postgres");
const temp = await fs.mkdtemp(path.join(os.tmpdir(), "suite-packaged-tools-"));
const dump = path.join(temp, "acceptance.dump");
const corrupt = path.join(temp, "corrupt.dump");
let report;

try {
  const provenance = JSON.parse(await fs.readFile(path.join(tools, "provenance.json"), "utf8"));
  if (provenance.status !== "verified" || provenance.postgresMajor !== 16) throw new Error("packaged tools provenance is not verified PostgreSQL 16");
  const dumpVersion = (await run(dumpBin, ["--version"])).stdout.trim();
  const restoreVersion = (await run(restoreBin, ["--version"])).stdout.trim();
  if (!dumpVersion.includes(provenance.postgresVersion) || !restoreVersion.includes(provenance.postgresVersion)) {
    throw new Error("packaged executable versions do not match packaged provenance");
  }
  const serverVersion = String((await sql(sourceUrl, "SHOW server_version")).rows[0].server_version);
  if (serverVersion.split(".")[0] !== String(provenance.postgresMajor)) throw new Error(`server/client major mismatch: ${serverVersion}`);

  await sql(sourceUrl, `
    DROP SCHEMA IF EXISTS packaged_tools_acceptance CASCADE;
    CREATE SCHEMA packaged_tools_acceptance;
    CREATE TABLE packaged_tools_acceptance.parent (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      exact_value bigint NOT NULL,
      label text NOT NULL UNIQUE
    );
    CREATE TABLE packaged_tools_acceptance.child (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      parent_id bigint NOT NULL REFERENCES packaged_tools_acceptance.parent(id),
      note text NOT NULL
    );
    INSERT INTO packaged_tools_acceptance.parent (id, exact_value, label)
      VALUES (41, 9007199254740993, 'تهران – café ☕');
    INSERT INTO packaged_tools_acceptance.child (parent_id, note)
      VALUES (41, 'بازگردانی امن');
    SELECT setval(pg_get_serial_sequence('packaged_tools_acceptance.parent', 'id'), 41, true);
  `);

  await run(dumpBin, ["--format=custom", "--no-owner", "--no-privileges", "--file", dump, sourceUrl]);
  await sql(adminUrl, `CREATE DATABASE ${restoredName}`);
  await run(restoreBin, ["--exit-on-error", "--no-owner", "--no-privileges", "--dbname", databaseUrl(restoredName), dump]);

  const restored = await sql(databaseUrl(restoredName), `
    SELECT p.id::text, p.exact_value::text, p.label, c.note,
      pg_get_serial_sequence('packaged_tools_acceptance.parent', 'id') AS sequence_name
    FROM packaged_tools_acceptance.parent p
    JOIN packaged_tools_acceptance.child c ON c.parent_id = p.id
    WHERE p.id = 41
  `);
  const row = restored.rows[0];
  if (!row || row.exact_value !== "9007199254740993" || row.label !== "تهران – café ☕" || row.note !== "بازگردانی امن" || !row.sequence_name) {
    throw new Error("restored UTF-8/bigint/FK/sequence acceptance values do not match");
  }
  const next = await sql(databaseUrl(restoredName), "INSERT INTO packaged_tools_acceptance.parent(exact_value,label) VALUES (1,'next') RETURNING id::text");
  if (BigInt(next.rows[0].id) <= 41n) throw new Error("restored identity sequence did not advance");

  const bytes = await fs.readFile(dump);
  await fs.writeFile(corrupt, bytes.subarray(0, Math.max(16, Math.floor(bytes.length / 3))));
  await sql(adminUrl, `CREATE DATABASE ${corruptName}`);
  await run(restoreBin, ["--exit-on-error", "--dbname", databaseUrl(corruptName), corrupt], { expectFailure: true });

  report = {
    schemaVersion: 1,
    status: "PASS",
    postgresToolsVersion: provenance.postgresVersion,
    serverVersion,
    artifact: provenance.artifact,
    checks: ["custom-format", "utf8", "exact-bigint", "foreign-key", "identity-sequence", "corruption-rejected"],
    generatedAt: new Date().toISOString(),
  };
  await fs.writeFile(output, `${JSON.stringify(report, null, 2)}\n`);
  console.log(`Packaged PostgreSQL tools acceptance passed (${provenance.postgresVersion}; server ${serverVersion}).`);
} finally {
  for (const name of [restoredName, corruptName]) {
    await sql(adminUrl, "SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = $1", [name]).catch(() => {});
    await sql(adminUrl, `DROP DATABASE IF EXISTS ${name}`).catch(() => {});
  }
  await sql(sourceUrl, "DROP SCHEMA IF EXISTS packaged_tools_acceptance CASCADE").catch(() => {});
  await fs.rm(temp, { recursive: true, force: true });
}
